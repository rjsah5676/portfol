const SEEN_KEY = "sketch_seen";
const SEEN_MAX = 400;

export function loadSeen(): Set<string> {
  try {
    return new Set(JSON.parse(localStorage.getItem(SEEN_KEY) ?? "[]") as string[]);
  } catch {
    return new Set();
  }
}

export function addSeen(word: string) {
  try {
    const k = normalizeAnswer(word);
    const list = (JSON.parse(localStorage.getItem(SEEN_KEY) ?? "[]") as string[]).filter(
      (x) => x !== k
    );
    list.push(k);
    localStorage.setItem(SEEN_KEY, JSON.stringify(list.slice(-SEEN_MAX)));
  } catch {}
}

/** 정답 비교용: 공백 제거, 소문자 */
export const normalizeAnswer = (s: string) => s.replace(/\s+/g, "").toLowerCase();

const CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ";

/** 힌트 단계별 표시: 0 = 글자 수만, 1 = 첫 글자, 2 = 첫 글자 + 나머지 초성 */
export function hintOf(word: string, level: number): string {
  return [...word]
    .map((ch, i) => {
      if (ch === " ") return " ";
      if (level >= 1 && i === 0) return ch;
      if (level >= 2) {
        const code = ch.charCodeAt(0) - 0xac00;
        if (code >= 0 && code <= 11171) return CHO[Math.floor(code / 588)];
        return ch;
      }
      return "○";
    })
    .join("");
}
