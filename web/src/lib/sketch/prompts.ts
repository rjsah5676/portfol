const pick = <T>(list: T[]) => list[Math.floor(Math.random() * list.length)];

/** 엉뚱한 제시어 n개 (서로 겹치지 않게) */
export function pickPrompts(n: number): string[] {
  const out = new Set<string>();
  let guard = 0;
  while (out.size < n && guard++ < 500) {
    // 다섯에 하나는 통째 장면, 나머지는 꾸밈말 + 대상
    out.add(Math.random() < 0.2 ? pick(SCENES) : `${pick(MODS)} ${pick(SUBJECTS)}`);
  }
  return [...out];
}

export const randomStarter = () => pick(RELAY_STARTERS);
