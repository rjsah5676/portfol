/** 호감 단계 이름 (관계마다) */
export function heartName(role: Role, aff: number) {
  const L =
    role === "crush"
      ? ["처음 본 사이", "아는 사이", "신경 쓰이는 사이", "설레는 사이", "썸"]
      : role === "sister"
        ? ["처음 본 꼬마", "아는 꼬마", "졸졸 따라옴", "단짝 남매", "최고의 오빠"]
        : ["처음 본 사이", "아는 사이", "친구", "절친", "평생 라이벌"];
  return L[aff >= 80 ? 4 : aff >= 55 ? 3 : aff >= 30 ? 2 : aff >= 10 ? 1 : 0];
}

